// --- Poll "once in a while" from any task to update ms accumulator ---
uint32_t LPTime_GetElapsedMs(void)
{
	static uint16_t g_ms_accum = 0;

    uint16_t now = HAL_LPTIM_ReadCounter(&hlptim1);
    uint16_t delta_ticks = (uint16_t)(now - g_last_cnt);   // handles 16-bit wrap
    g_last_cnt = now;

    // Convert 1024 Hz ticks to ms exactly: ms += ticks * 1000 / 1024
    // Use 32-bit math with widening to avoid overflow on the multiply.
    g_ms_accum = (uint32_t)(((uint32_t)delta_ticks * 1000U) >> 10); // /1024 via >>10
    // Note: this floors fractional ms; error is <1 ms per poll.

    return g_ms_accum;
}
